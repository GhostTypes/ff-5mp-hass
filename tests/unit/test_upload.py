def make_3mf(
    filaments=((1, "PLA", "#FF0000"), (2, "PETG", "#000000")),
    *,
    model="Flashforge-Creator-5-Pro",
    plates=(1,),
) -> bytes:
    """A sliced 3MF using the given (filament id, material, color) filaments."""
    filament_xml = "".join(
        f'<filament id="{fid}" type="{material}" color="{color}" used_m="1.0" used_g="3.5" />'
        for fid, material, color in filaments
    )
    slice_info = (
        '<?xml version="1.0" encoding="UTF-8"?><config><plate>'
        '<metadata key="index" value="1"/>'
        f'<metadata key="printer_model_id" value="{model}"/>'
        '<metadata key="prediction" value="1698"/><metadata key="weight" value="7.0"/>'
        f"{filament_xml}"
        '<warning msg="bed_temperature_too_high_than_filament" level="3" error_code="1000C001" />'
        "</plate></config>"
    )
    buffer = BytesIO()
    with zipfile.ZipFile(buffer, "w") as archive:
        archive.writestr("Metadata/slice_info.config", slice_info)
        for index in plates:
            archive.writestr(f"Metadata/plate_{index}.gcode", GCODE)
            archive.writestr(f"Metadata/plate_{index}.png", b"\x89PNG-thumb")
    return buffer.getvalue()


def make_machine_info(
    *,
    family="creator5_pro",
    slots=((1, "PLA", "#FF0000"), (2, "PETG", "#000000")),
    state="ready",
):
    """Machine info for a printer family with the given (slot, material, color) slots."""
    info = Mock()
    info.is_creator5 = family in ("creator5", "creator5_pro")
    info.is_creator5_pro = family == "creator5_pro"
    info.is_ad5x = family == "ad5x"
    info.is_pro = family in ("5m_pro", "creator5_pro")
    info.machine_state = Mock(value=state)
    info.matl_station_info.slot_infos = [
        Mock(
            slot_id=slot_id,
            has_filament=material is not None,
            material_name=material or "",
            material_color=color or "",
        )
        for slot_id, material, color in slots
    ]
    return info


