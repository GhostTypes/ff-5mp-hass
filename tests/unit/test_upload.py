def start_msg(upload_id, mappings=None, **extra):
    return {
        "id": 7,
        "type": "flashforge/upload/start",
        "entry_id": ENTRY_ID,
        "upload_id": upload_id,
        "leveling": False,
        "material_mappings": mappings if mappings is not None else [],
        **extra,
    }


async def test_start_sends_the_validated_mappings_and_cleans_up():
    client = make_client()
    hass = make_hass(client=client)
    payload = await stage(hass)
    conn = connection()

    await ws_upload_start(
        hass,
        conn,
        start_msg(
            payload["upload_id"],
            [{"tool_id": 0, "slot_id": 1}, {"tool_id": 1, "slot_id": 2}],
        ),
    )

    conn.send_error.assert_not_called()
    result = conn.send_result.call_args.args[1]
    assert result["started"] is True
    assert result["file_name"] == "print.3mf"
    start = client.job_control.start_creator5_job.await_args.args[0]
    assert [(m.tool_id, m.slot_id, m.material_name) for m in start.material_mappings] == [
        (0, 1, "PLA"),
        (1, 2, "PETG"),
    ]
    assert get_store(hass).get(payload["upload_id"], ENTRY_ID) is None
    hass.data[DOMAIN][ENTRY_ID]["coordinator"].async_request_refresh.assert_awaited()


